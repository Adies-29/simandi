//    Load dong
        private void loadTable() {

    DefaultTableModel model =
            (DefaultTableModel) tblUser.getModel();

    model.setRowCount(0);

    List<Anggota1> list =
            service.tampilSemuaAnggota();

    for (Anggota1 a : list) {

        // SKIP kalau data kosong
        if (a == null
                || a.getNim() == null
                || a.getNim().trim().isEmpty()) {
            continue;
        }

        Object[] row = {
            a.getUidRfid(),
            a.getNamaLengkap(),
            a.getNim(),
            a.getKelas(),
            a.getJurusan(),
            a.getStatus(),
            "Hapus"
        };

        model.addRow(row);
    }
}
     
