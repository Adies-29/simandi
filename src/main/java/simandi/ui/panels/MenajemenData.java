//     Searchh 
   private void searchData() {

    String key = txtSearch.getText();

    DefaultTableModel model =
            (DefaultTableModel) tblUser.getModel();

    model.setRowCount(0);

    List<Anggota1> list =
            service.searchAnggota(key);

    for (Anggota1 a : list) {

        // SKIP data kosong
        if (a == null
                || a.getNim() == null
                || a.getNim().trim().isEmpty()) {
            continue;
        }

        Object[] row = {
            a.getUidRfid(),
            a.getNamaLengkap(),
            a.getNim(),
            a.getKelas(),
            a.getJurusan(),
            a.getStatus(),
            "Hapus"
        };

        model.addRow(row);
    }
}
    
